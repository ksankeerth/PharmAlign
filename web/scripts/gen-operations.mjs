// Writes src/api/operations.ts from the server contract: one entry per operation,
// with its method, path, the views allowed to call it and whether it is simulation-only.
// Run through `npm run gen:api` (after openapi-typescript writes src/api/schema.ts).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "../../contracts/openapi/server.yaml");
const outPath = resolve(here, "../src/api/operations.ts");

const spec = yaml.load(readFileSync(specPath, "utf8"));
const methods = ["get", "post", "put", "patch", "delete"];
const rows = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    rows.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? "",
      tag: (op.tags ?? [""])[0],
      views: op["x-allowed-views"] ?? null,
      simulationOnly: op["x-simulation-only"] === true,
      stream: Boolean(op.responses?.["200"]?.content?.["text/event-stream"]),
    });
  }
}

const lines = [
  "// Generated by scripts/gen-operations.mjs from contracts/openapi/server.yaml. Do not edit.",
  "/* eslint-disable */",
  'import type { operations } from "./schema";',
  "",
  'export type View = "platform_admin" | "process_owner" | "case_officer" | "decision_maker" | "auditor";',
  "",
  "export interface OperationMeta {",
  '  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";',
  "  path: string;",
  "  summary: string;",
  "  tag: string;",
  "  /** Null means the server does not restrict by view (system and connector calls). */",
  "  views: readonly View[] | null;",
  "  simulationOnly: boolean;",
  "  stream: boolean;",
  "}",
  "",
  `export const CONTRACT_TITLE = ${JSON.stringify(spec.info.title)};`,
  `export const CONTRACT_VERSION = ${JSON.stringify(spec.info.version)};`,
  "",
  "export const OPERATIONS = {",
  ...rows.map(
    (r) =>
      `  ${r.id}: { method: "${r.method}", path: ${JSON.stringify(r.path)}, summary: ${JSON.stringify(r.summary)}, tag: ${JSON.stringify(r.tag)}, views: ${r.views ? JSON.stringify(r.views) : "null"}, simulationOnly: ${r.simulationOnly}, stream: ${r.stream} },`,
  ),
  "} as const satisfies Record<keyof operations, OperationMeta>;",
  "",
  "export type OperationId = keyof typeof OPERATIONS;",
  "",
];
writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${rows.length} operations to ${outPath}`);
